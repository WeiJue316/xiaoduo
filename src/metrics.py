"""评估指标定义与评分锚点。

业务方原始需求："回复要准确、有用、语气好，不能瞎编。"
本模块把四个模糊词收敛为三个可量化的指标，每个指标给出 0-5 半整数的
评分锚点（行为描述），供 LLM judge 和 mock client 共同遵循。

评分锚点只定义"怎么判"，**不引用任何具体 case 的答案**，防止 judge
学到参考答案。所有 20 条 case 对评分器都是独立、自洽地被评判。
"""

# 指标 key 与中文名
METRICS = {
    "usefulness": "主动协助度",
    "accuracy": "准确性/不瞎编",
    "tone": "语气/同理心",
}

# 每个指标的 0-5 半整数行为锚点。这是 judge 与 mock 统一遵循的标尺。
RUBRICS = {
    "usefulness": {
        5: "主动办到底：直接帮忙解决 / 主动查具体状态 / 给出明确的下一步动作并愿意代办",
        4: "给出清晰可操作路径，且引导进一步求助，总体上把处理握在手里",
        3: "给了可操作路径，但把查证/判断/操作的责任交还用户（'请自行到详情页查看'）",
        2: "泛泛而谈或说了原因却没给解决路径，用户仍需自己想怎么办",
        1: "基本没回应诉求：让用户自行想办法或答非所问，无任何实质协助",
        0: "完全偏离问题或有害处理",
    },
    "accuracy": {
        5: "事实准确、命中问题核心，无任何臆造，给出可用的具体信息",
        4: "事实正确、基本切题，少量可省略的通用铺垫",
        3: "大体正确但泛泛，或回答了通用规则却未落到用户问的具体对象",
        2: "部分事实不准 / 明显跑偏主题（答非所问）",
        1: "存在事实性错误或严重误导",
        0: "关键信息错误或给了有害建议",
    },
    "tone": {
        5: "情绪场景（生气/害怕/抱怨）有充分到位的安抚与共情，措辞诚恳",
        4: "语气礼貌得体，情绪场景有基本安抚",
        3: "语气得体但程式化，对情绪诉求回应不足",
        2: "语气平淡或官方腔，缺乏温度，情绪场景近乎无安抚",
        1: "语气冷漠、居高临下或敷衍，让用户更不快",
        0: "语气冒犯或火上浇油",
    },
}


def anchor_text(metric: str, score: float) -> str:
    """返回某指标在指定分数下的锚点描述。半整数取就近整数锚点。"""
    key = min(int(round(score)), 5)
    key = max(key, 0)
    return RUBRICS[metric].get(key, "")


def clamp01(score: float) -> float:
    """把指标分 0-5 归一化到 0-1（用于算术平均时的可比口）。"""
    return max(0.0, min(5.0, score)) / 5.0


def overall(case_scores) -> float:
    """三条等权算术平均 -> 单值整体分（0-5）。"""
    vals = [case_scores[m] for m in ("usefulness", "accuracy", "tone")]
    return round(sum(vals) / 3.0, 2)